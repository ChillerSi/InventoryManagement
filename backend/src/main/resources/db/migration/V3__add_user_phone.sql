-- =============================================================================
-- 义采通采购管理系统 - V3 用户手机号
--
-- 说明：
-- 1. 注册主账号必须填写符合中国大陆移动号码格式的手机号。
-- 2. 子账号手机号为选填。
-- 3. 手机号不建立唯一索引，允许不同账号登记相同的联系号码。
-- 4. 既有账号没有历史手机号，因此字段允许为空。
-- =============================================================================

ALTER TABLE users
    ADD COLUMN phone VARCHAR(20) NULL
        COMMENT '联系手机号；主账号注册时必填，子账号选填，不校验唯一性'
        AFTER password;

CREATE INDEX idx_users_tenant_phone
    ON users (tenant_id, phone)
    COMMENT '按租户和手机号辅助查询账号；不限制手机号重复';
