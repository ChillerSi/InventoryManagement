-- =============================================================================
-- V4：为采购任务增加“急采”业务标识。
--
-- 业务说明：
-- 1. 管理员或运营创建采购任务时可以选择是否急采；
-- 2. 急采状态随采购任务持久化，刷新页面、跨天展示和多账号查看时不会丢失；
-- 3. 该字段仅用于任务优先级提示，不改变采购完成、删除和权限规则。
-- =============================================================================

ALTER TABLE purchase_orders
    ADD COLUMN urgent TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '是否急采：0=普通采购，1=急采；急采任务在今日采购卡片显示火焰标识'
        AFTER plan_qty;
